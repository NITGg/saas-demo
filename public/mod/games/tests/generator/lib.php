 */
class mod_games_generator extends testing_module_generator {

    /**
     * Create a Game activity; plays Math Race unless told otherwise.
     *
     * @param array|stdClass|null $record
     * @param array|null $options
     * @return stdClass
     */
    public function create_instance($record = null, ?array $options = null) {
        $record = (object) (array) $record;
        $record->gameid = $record->gameid ?? 'math-race';
        $record->showhublink = $record->showhublink ?? 0;
        $record->completionplays = $record->completionplays ?? 0;
        $record->completionscore = $record->completionscore ?? 0;
        return parent::create_instance($record, (array) $options);
    }
}
